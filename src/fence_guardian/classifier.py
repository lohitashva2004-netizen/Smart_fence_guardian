"""Event classifiers: a Random Forest (gateway), a depth-limited tree (edge MCU), and a linear baseline."""
from __future__ import annotations

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, f1_score, precision_recall_fscore_support
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.tree import DecisionTreeClassifier

from .config import CLASSES, ENERGIZER, SEED


def train_models(X, y, seed: int = SEED) -> dict:
    return {
        "Random Forest (gateway)": RandomForestClassifier(n_estimators=200, min_samples_leaf=2, random_state=seed, n_jobs=-1).fit(X, y),
        "Decision Tree (edge, depth 6)": DecisionTreeClassifier(max_depth=6, min_samples_leaf=5, random_state=seed).fit(X, y),
        "Logistic Regression": make_pipeline(StandardScaler(), LogisticRegression(max_iter=3000)).fit(X, y),
    }


def evaluate(model, X, y) -> dict:
    pred = model.predict(X)
    p, r, f, _ = precision_recall_fscore_support(y, pred, labels=range(len(CLASSES)), zero_division=0)
    return {
        "accuracy": float(np.mean(pred == y)),
        "macro_f1": float(f1_score(y, pred, average="macro")),
        "energizer_precision": float(p[ENERGIZER]),
        "energizer_recall": float(r[ENERGIZER]),
        "per_class_f1": dict(zip(CLASSES, map(float, f))),
        "confusion_matrix": confusion_matrix(y, pred, labels=range(len(CLASSES))).tolist(),
    }


def export_tree_to_c(tree: DecisionTreeClassifier, feature_names: list[str], class_names: list[str]) -> str:
    """Emit a dependency-free C header implementing the fitted tree (for the ESP32 firmware).

    Comparisons use float features against double thresholds, matching scikit-learn's float32 semantics.
    """
    t = tree.tree_
    classes = tree.classes_

    def node(i: int, depth: int) -> str:
        pad = "    " * depth
        if t.children_left[i] == -1:
            return f"{pad}return {int(classes[int(np.argmax(t.value[i][0]))])};\n"
        thr = repr(float(t.threshold[i]))
        return (f"{pad}if (f[{int(t.feature[i])}] <= {thr}) {{\n{node(t.children_left[i], depth + 1)}"
                f"{pad}}} else {{\n{node(t.children_right[i], depth + 1)}{pad}}}\n")

    enum = "\n".join(f"    FG_FEAT_{n.upper()} = {i}," for i, n in enumerate(feature_names))
    cls = "\n".join(f"    FG_CLASS_{n.upper()} = {i}," for i, n in enumerate(class_names))
    return (
        "/* AUTO-GENERATED by fence_guardian.classifier.export_tree_to_c - do not edit by hand. */\n"
        "#ifndef FENCE_CLASSIFIER_H\n#define FENCE_CLASSIFIER_H\n\n"
        f"enum {{\n{enum}\n    FG_N_FEATURES = {len(feature_names)}\n}};\n\n"
        f"enum {{\n{cls}\n    FG_N_CLASSES = {len(class_names)}\n}};\n\n"
        "static inline int fg_classify(const float f[FG_N_FEATURES]) {\n"
        f"{node(0, 1)}}}\n\n#endif /* FENCE_CLASSIFIER_H */\n"
    )
